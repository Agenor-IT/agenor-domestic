create or replace function public.dom_onboarding_complete(
  p_persona_padre_id integer,
  p_account_name text,
  p_opening_balance numeric
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_account_id bigint;
begin
  perform public.dom_assert_tenant_access(p_persona_padre_id);
  if length(btrim(coalesce(p_account_name, ''))) = 0 then
    raise exception 'El nombre de la cuenta es obligatorio' using errcode = '22023';
  end if;

  insert into public.dom_accounts (
    persona_padre_id, name, kind, opening_balance, created_by, updated_by
  ) values (
    p_persona_padre_id, btrim(p_account_name), 'cash',
    coalesce(p_opening_balance, 0), auth.uid(), auth.uid()
  )
  on conflict (persona_padre_id, name) do update
    set updated_at = public.dom_accounts.updated_at
  returning id into v_account_id;

  insert into public.dom_categories (
    persona_padre_id, name, direction, color, created_by, updated_by
  ) values
    (p_persona_padre_id, 'Trabajo', 'income', '#3D8B6D', auth.uid(), auth.uid()),
    (p_persona_padre_id, 'Hogar', 'expense', '#D97757', auth.uid(), auth.uid()),
    (p_persona_padre_id, 'Comida', 'expense', '#E6A23C', auth.uid(), auth.uid()),
    (p_persona_padre_id, 'Transporte', 'expense', '#6376B8', auth.uid(), auth.uid()),
    (p_persona_padre_id, 'Otros', 'expense', '#75808A', auth.uid(), auth.uid())
  on conflict (persona_padre_id, name, direction) do nothing;

  return jsonb_build_object('account_id', v_account_id);
end;
$$;

