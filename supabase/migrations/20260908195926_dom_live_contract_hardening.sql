create table if not exists public.dom_entries (
  id bigint generated by default as identity primary key,
  persona_padre_id integer not null,
  account_id bigint not null references public.dom_accounts(id),
  category_id bigint references public.dom_categories(id),
  direction text not null check (direction in ('income', 'expense')),
  flow_status text not null check (flow_status in ('real', 'projected')),
  amount numeric(14, 2) not null check (amount > 0),
  description text not null check (length(btrim(description)) > 0),
  occurred_on date not null default current_date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  updated_by uuid default auth.uid(),
  unidad_negocio_id bigint
);

do $$
begin
  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conname = 'dom_accounts_persona_name_key'
      and conrelid = 'public.dom_accounts'::regclass
  ) then
    alter table public.dom_accounts
      add constraint dom_accounts_persona_name_key unique (persona_padre_id, name);
  end if;

  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conname = 'dom_categories_persona_name_direction_key'
      and conrelid = 'public.dom_categories'::regclass
  ) then
    alter table public.dom_categories
      add constraint dom_categories_persona_name_direction_key
      unique (persona_padre_id, name, direction);
  end if;
end
$$;

