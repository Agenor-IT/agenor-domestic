create or replace function public.dom_entry_create(
  p_persona_padre_id integer,
  p_account_id bigint,
  p_category_id bigint,
  p_direction text,
  p_flow_status text,
  p_amount numeric,
  p_description text,
  p_occurred_on date
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_entry_id bigint;
begin
  perform public.dom_assert_tenant_access(p_persona_padre_id);

  if p_amount is null or p_amount <= 0 then
    raise exception 'El importe debe ser mayor a cero' using errcode = '22023';
  end if;
  if length(btrim(coalesce(p_description, ''))) = 0 then
    raise exception 'La descripcion es obligatoria' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.dom_accounts a
    where a.id = p_account_id
      and a.persona_padre_id = p_persona_padre_id
      and not a.is_archived
  ) then
    raise exception 'La cuenta no pertenece al contexto activo' using errcode = '42501';
  end if;
  if p_category_id is not null and not exists (
    select 1 from public.dom_categories c
    where c.id = p_category_id
      and c.persona_padre_id = p_persona_padre_id
      and not c.is_archived
      and c.direction = p_direction
  ) then
    raise exception 'La categoria no pertenece al contexto activo' using errcode = '42501';
  end if;

  insert into public.dom_entries (
    persona_padre_id, account_id, category_id, direction, flow_status,
    amount, description, occurred_on, created_by, updated_by
  ) values (
    p_persona_padre_id, p_account_id, p_category_id, p_direction, p_flow_status,
    p_amount, btrim(p_description), coalesce(p_occurred_on, current_date),
    auth.uid(), auth.uid()
  )
  returning id into v_entry_id;

  return jsonb_build_object('id', v_entry_id);
end;
$$;

create or replace function public.dom_entries_list(
  p_persona_padre_id integer,
  p_limit integer default 50
)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $$
begin
  perform public.dom_assert_tenant_access(p_persona_padre_id);
  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', e.id,
      'account_id', e.account_id,
      'account_name', a.name,
      'category_id', e.category_id,
      'category_name', c.name,
      'direction', e.direction,
      'flow_status', e.flow_status,
      'amount', e.amount,
