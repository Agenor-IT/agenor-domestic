    join public.dom_accounts a
      on a.id = e.account_id
     and a.persona_padre_id = p_persona_padre_id
    left join public.dom_categories c
      on c.id = e.category_id
     and c.persona_padre_id = p_persona_padre_id
  ), '[]'::jsonb);
end;
$$;

create or replace function public.dom_dashboard_summary(
  p_persona_padre_id integer,
  p_end_date date default (current_date + 30)
)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $$
declare
  v_current_balance numeric(14, 2);
  v_month_income numeric(14, 2);
  v_month_expense numeric(14, 2);
  v_projected_balance numeric(14, 2);
begin
  perform public.dom_assert_tenant_access(p_persona_padre_id);

  select
    coalesce((select sum(a.opening_balance)
      from public.dom_accounts a
      where a.persona_padre_id = p_persona_padre_id and not a.is_archived), 0)
    + coalesce((select sum(case when e.direction = 'income' then e.amount else -e.amount end)
      from public.dom_entries e
      where e.persona_padre_id = p_persona_padre_id
        and e.flow_status = 'real'
        and e.occurred_on <= current_date), 0)
  into v_current_balance;

  select
    coalesce(sum(case when direction = 'income' then amount else 0 end), 0),
    coalesce(sum(case when direction = 'expense' then amount else 0 end), 0)
  into v_month_income, v_month_expense
  from public.dom_entries
  where persona_padre_id = p_persona_padre_id
    and flow_status = 'real'
    and occurred_on >= date_trunc('month', current_date)::date
    and occurred_on <= current_date;

  select v_current_balance
    + coalesce(sum(case when direction = 'income' then amount else -amount end), 0)
  into v_projected_balance
  from public.dom_entries
  where persona_padre_id = p_persona_padre_id
    and flow_status = 'projected'
    and occurred_on > current_date
    and occurred_on <= greatest(p_end_date, current_date);

  return jsonb_build_object(
    'current_balance', v_current_balance,
    'month_income', v_month_income,
    'month_expense', v_month_expense,
    'projected_balance', v_projected_balance,
    'upcoming', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', e.id,
        'description', e.description,
        'amount', e.amount,
        'direction', e.direction,
        'flow_status', e.flow_status,
        'occurred_on', e.occurred_on,
        'account_name', a.name,
        'category_name', c.name
      ) order by e.occurred_on, e.id)
      from (
        select * from public.dom_entries
        where persona_padre_id = p_persona_padre_id
          and occurred_on >= current_date
          and occurred_on <= greatest(p_end_date, current_date)
        order by occurred_on, id
        limit 8
      ) e
      join public.dom_accounts a
        on a.id = e.account_id
       and a.persona_padre_id = p_persona_padre_id
      left join public.dom_categories c
        on c.id = e.category_id
       and c.persona_padre_id = p_persona_padre_id
    ), '[]'::jsonb),
    'weeks', coalesce((
      select jsonb_agg(jsonb_build_object(
        'week_start', w.week_start,
        'net_amount', coalesce((
          select sum(case when e.direction = 'income' then e.amount else -e.amount end)
          from public.dom_entries e
          where e.persona_padre_id = p_persona_padre_id
            and e.flow_status = 'projected'
            and e.occurred_on >= w.week_start
            and e.occurred_on < w.week_start + 7
        ), 0)
      ) order by w.week_start)
      from generate_series(
        date_trunc('week', current_date)::date,
        least(
          date_trunc('week', greatest(p_end_date, current_date))::date,
          date_trunc('week', current_date)::date + 28
        ),
        interval '7 days'
      ) as w(week_start)
    ), '[]'::jsonb)
  );
end;
$$;

create or replace function public.dom_allocate_payment(
  p_persona_padre_id integer,
  p_debt_id uuid,
  p_amount numeric
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_debt public.dom_debts%rowtype;
  v_allocated_arrears numeric(18, 2) := 0;
  v_allocated_principal numeric(18, 2) := 0;
  v_remaining numeric(18, 2);
begin
  perform public.dom_assert_tenant_access(p_persona_padre_id);
  if p_amount is null or p_amount <= 0 then
    raise exception 'El importe debe ser mayor a cero' using errcode = '22023';
  end if;

  select * into v_debt
  from public.dom_debts
  where id = p_debt_id
    and persona_padre_id = p_persona_padre_id
  for update;

  if not found then
    raise exception 'Deuda no encontrada para el tenant especificado' using errcode = 'P0002';
  end if;
  if p_amount > v_debt.arrears_balance + v_debt.total_principal then
    raise exception 'El importe supera el saldo total de la deuda' using errcode = '22023';
  end if;

  v_remaining := p_amount;
  v_allocated_arrears := least(v_debt.arrears_balance, v_remaining);
  v_remaining := v_remaining - v_allocated_arrears;
  v_allocated_principal := least(v_debt.total_principal, v_remaining);

  insert into public.dom_debt_payments (
    persona_padre_id,
    debt_id,
    amount_paid,
    payment_date,
    allocated_to_principal,
    allocated_to_arrears
  ) values (
    p_persona_padre_id,
    p_debt_id,
    p_amount,
    current_date,
    v_allocated_principal,
    v_allocated_arrears
  );

  update public.dom_debts
  set arrears_balance = arrears_balance - v_allocated_arrears,
      total_principal = total_principal - v_allocated_principal
  where id = p_debt_id
    and persona_padre_id = p_persona_padre_id;

  insert into public.dom_audit_log (
    persona_padre_id,
    user_id,
    entity_type,
    entity_id,
    action,
    new_value
  ) values (
    p_persona_padre_id,
    auth.uid(),
    'dom_debts',
    p_debt_id::text,
    'ALLOCATE_PAYMENT',
    jsonb_build_object(
      'amount_paid', p_amount,
      'allocated_to_arrears', v_allocated_arrears,
      'allocated_to_principal', v_allocated_principal
    )
  );

  return jsonb_build_object(
    'success', true,
    'allocated_arrears', v_allocated_arrears,
    'allocated_principal', v_allocated_principal,
    'remaining_arrears', v_debt.arrears_balance - v_allocated_arrears,
    'remaining_principal', v_debt.total_principal - v_allocated_principal
  );
end;
$$;

