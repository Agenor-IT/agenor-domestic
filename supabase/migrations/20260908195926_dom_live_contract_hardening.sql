create or replace function public.dom_context_get(p_persona_padre_id integer default null)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $$
declare
  v_persona_padre_id integer;
begin
  if p_persona_padre_id is null then
    v_persona_padre_id := public.dom_current_persona_padre_id();
  else
    perform public.dom_assert_tenant_access(p_persona_padre_id);
    v_persona_padre_id := p_persona_padre_id;
  end if;

  return jsonb_build_object('persona_padre_id', v_persona_padre_id);
end;
$$;

